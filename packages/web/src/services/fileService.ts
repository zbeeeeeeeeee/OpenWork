import { i18n } from '../locales';
import type { DisplayMessage } from '@openwork/agent';

export interface FileEntry {
  name: string;
  path: string;
  isDirectory: boolean;
  size?: number;
  modifiedAt?: number;
  children?: FileEntry[];
}

export interface DirectoryEntry {
  name: string;
  path: string;
  isDirectory: true;
  hidden?: boolean;
}

export interface DirectoryBrowseResult {
  path: string;
  parent: string | null;
  breadcrumbs: DirectoryEntry[];
  entries: DirectoryEntry[];
  truncated: boolean;
}

/** 从绝对路径构造面包屑（server /browse 不返回 breadcrumbs 时的兜底） */
function buildBreadcrumbsFromPath(absPath: string): DirectoryEntry[] {
  const normalized = absPath.replace(/\\/g, '/');
  const parts = normalized.split('/').filter(Boolean);
  const crumbs: DirectoryEntry[] = [];
  if (!normalized.startsWith('/')) {
    let acc = parts[0] + '/';
    crumbs.push({ name: acc, path: acc, isDirectory: true });
    for (const part of parts.slice(1)) {
      acc = acc.replace(/\/$/, '') + '/' + part;
      crumbs.push({ name: part, path: acc, isDirectory: true });
    }
  } else {
    crumbs.push({ name: '/', path: '/', isDirectory: true });
    let p = '';
    for (const part of parts) {
      p += '/' + part;
      crumbs.push({ name: part, path: p, isDirectory: true });
    }
  }
  return crumbs;
}

/**
 * 文件服务客户端接口
 *
 * 增加了 openFolder / openFile / saveFileAs 等 UI 交互方法。
 * 三种实现分别对应 Electron IPC、Server REST API、Browser File System Access API。
 */
export interface FileServiceClient {
  rootName?: string;
  readFile(path: string): Promise<string>;
  readFileBuffer(path: string): Promise<ArrayBuffer>;
  writeFile(path: string, content: string): Promise<void>;
  deleteFile(path: string): Promise<void>;
  readDir(path: string): Promise<FileEntry[]>;
  createDir(path: string): Promise<void>;
  deleteDir(path: string, recursive?: boolean): Promise<void>;
  exists(path: string): Promise<boolean>;
  stat(path: string): Promise<FileEntry>;
  rename(oldPath: string, newPath: string): Promise<void>;
  openFolderPath?(path: string): Promise<string | null>;
  openFolder(): Promise<string | null>;
  openFile(): Promise<{ path: string } | null>;
  saveFileAs?(path: string, content: string): Promise<string | null>;
  browseFilesystem(path: string): Promise<{ path: string; parent: string; entries: FileEntry[] }>;
  getWorkspaceRoots(): Promise<FileEntry[]>;
  openWorkspace(rootPath: string, providerConfig?: Record<string, unknown>, lightweight?: boolean): Promise<WorkspaceInfo>;
  closeWorkspace(workspaceId: string): Promise<void>;
  updateWorkspace(workspaceId: string, data: { openTabs?: StoredTabInfo[]; activeTabPath?: string; workspaceRoot?: string }): Promise<void>;
  getWorkspaceSessions(workspaceId: string, workspaceRoot?: string): Promise<WorkspaceAgentSession[]>;
  saveWorkspaceSession(workspaceId: string, session: WorkspaceAgentSession, workspaceRoot?: string): Promise<void>;
  deleteWorkspaceSession(workspaceId: string, sessionId: string, workspaceRoot?: string): Promise<void>;
  /** 拉取单个 session 的展示用消息(后端 memory.projectToDisplay 产出) */
  getSessionMessages(workspaceId: string, sessionId: string, workspaceRoot?: string): Promise<DisplayMessage[]>;
  setWorkspaceRoot?(root: string): void;
  listDirectories?(path?: string): Promise<DirectoryBrowseResult>;
  createDirectory?(parent: string, name: string): Promise<DirectoryEntry>;
}

export interface StoredTabInfo {
  path: string;
  cursorLine?: number;
  cursorColumn?: number;
}

export interface WorkspaceAgentSession {
  id: string;
  name: string;
  nameAutoGenerated: boolean;
  createdAt: number;
  lastMessageAt?: number;
}

